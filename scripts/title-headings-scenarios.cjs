const assert=require('node:assert/strict');
const path=require('node:path');
const {app,root,ready,makeWindow,settle}=require('./lib/electron-harness.cjs');
(async()=>{let win;try{
    await ready();win=makeWindow(1280,900);
    await win.loadFile(path.join(root,'src/renderer/editor.html'),{query:{new:'true',type:'title'}});await settle(win);
    await win.page.evaluate(async()=>{
        const editor=mollyEditor.titleEditor,project=mollyEditor.getActiveProject();await project.prefixLoadPromise;
        if(editor.currentRow!==0)throw Error('New projects must select the first heading');
    });
    await win.page.locator('[data-title-row-add]').click();
    await win.page.locator('[data-title-row-text]').fill('SECOND');
    await win.page.locator('[data-title-field="role"]').selectOption('top');
    await win.page.locator('[data-title-field="spacing"]').fill('2');
    await win.page.locator('[data-title-field="spacing"]').press('Tab');
    await win.page.locator('[data-title-field="depth"]').fill('12');
    await win.page.locator('[data-title-field="depth"]').press('Tab');
    assert.equal(await win.page.evaluate(()=>mollyEditor.getActiveProject().titleData.text),'MINECRAFT\nSECOND');
    await win.page.locator('[data-title-row]').selectOption('0');
    assert.equal(await win.page.locator('[data-title-row-text]').inputValue(),'MINECRAFT');
    assert.notEqual(await win.page.locator('[data-title-field="spacing"]').inputValue(),'2');
    assert.equal(await win.page.locator('[data-title-field="depth"]').inputValue(),'22');
    await win.page.locator('[data-title-row-remove]').click();
    assert.equal(await win.page.locator('[data-title-row-text]').inputValue(),'SECOND');
    assert.equal(await win.page.locator('[data-title-field="role"]').inputValue(),'top');
    assert.equal(await win.page.locator('[data-title-field="spacing"]').inputValue(),'2');
    assert.equal(await win.page.locator('[data-title-field="depth"]').inputValue(),'12');
    assert.equal(await win.page.locator('[data-title-row-remove]').isDisabled(),true);
    await win.page.locator('#btn-undo').click();
    await win.page.waitForFunction(()=>mollyEditor.getActiveProject().titleData.text==='MINECRAFT\nSECOND');
    await win.page.locator('[data-title-row-add]').click();
    assert.equal(await win.page.locator('[data-title-row-add]').isDisabled(),true);
    await win.page.locator('[data-title-row-text]').fill('THIRD');
    await win.page.locator('[data-title-field="role"]').selectOption('small');
    await win.page.locator('[data-title-row]').selectOption('1');
    assert.equal(await win.page.locator('[data-title-row-text]').inputValue(),'SECOND');
    assert.equal(await win.page.locator('[data-title-field="role"]').inputValue(),'top');
    assert.deepEqual(win.__testErrors,[]);console.log('PASS heading selection, separate text and styles, add/delete, role and undo');
}catch(error){console.error(error);process.exitCode=1;}finally{win?.destroy();app.exit(process.exitCode||0);}})();
