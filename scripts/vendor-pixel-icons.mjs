// Usage: node scripts/vendor-pixel-icons.mjs <unpacked pixelarticons package folder>
// The curated manifest is versioned; no package code or network runs in the app.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.resolve(process.argv[2] || '.test-output/pixelarticons-source/package');
const manifest = JSON.parse(await readFile(path.join(root, 'scripts/data/minecraft-icon-map.json'), 'utf8'));
const info = JSON.parse(await readFile(path.join(source, 'package.json'), 'utf8'));
if (info.version !== manifest.version) throw new Error(`Expected pixelarticons ${manifest.version}`);
const drawings = { ...manifest.custom };
for (const [glyph, filename] of Object.entries(manifest.sources)) {
    const svg = await readFile(path.join(source, 'svg', `${filename}.svg`), 'utf8');
    if (!/viewBox="0 0 24 24"/.test(svg) || /script|foreignObject|href=|\bon\w+=|<image|<text/.test(svg)) throw new Error(`Unsafe or inconsistent icon: ${filename}`);
    drawings[glyph] = svg.replace(/^[\s\S]*?<svg\b[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').trim();
}
for (const [name, glyph] of Object.entries(manifest.aliases)) {
    if (!drawings[glyph]) throw new Error(`No drawing for ${name}: ${glyph}`);
}
await writeFile(path.join(root, 'src/renderer/js/ui/PixelIconData.mjs'),
    `// Curated Pixelarticons ${manifest.version}, MIT — Gerrit Halfmann. ${manifest.source}\n`
    + '// Generated by scripts/vendor-pixel-icons.mjs. Application-specific additions share its 24px grid.\n'
    + `export const pixelDrawings = Object.freeze(${JSON.stringify(drawings, null, 2)});\n`
    + `export const pixelAliases = Object.freeze(${JSON.stringify(manifest.aliases, null, 2)});\n`);
const licenseDir = path.join(root, 'src/renderer/assets/icons/pixelarticons');
await mkdir(licenseDir, { recursive: true });
await writeFile(path.join(licenseDir, 'LICENSE.txt'), await readFile(path.join(source, 'LICENSE')));
console.log(`Vendored ${Object.keys(drawings).length} drawings for ${Object.keys(manifest.aliases).length} interface symbols`);
